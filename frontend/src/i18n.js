// A small compatibility layer for page-specific literal labels that are not passed
// through the shared UI primitives yet. Raw monospace/log content is intentionally
// excluded so diagnostics remain verbatim.
export function installDocumentTranslator(language, root = typeof document !== "undefined" ? document.body : null) {
  if (!root || typeof MutationObserver === "undefined") return () => {};
  const sourceByNode = new WeakMap();
  const outputByNode = new WeakMap();

  const scan = () => {
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    let node;
    while ((node = walker.nextNode())) nodes.push(node);
    nodes.forEach((textNode) => {
      const parent = textNode.parentElement;
      if (!parent || parent.closest("script,style,.font-mono,.mono,[data-no-translate]")) return;
      const current = textNode.nodeValue || "";
      const previousOutput = outputByNode.get(textNode);
      if (previousOutput !== undefined && current !== previousOutput) sourceByNode.set(textNode, current);
      const source = sourceByNode.get(textNode) || current;
      sourceByNode.set(textNode, source);
      const output = translate(source, language);
      outputByNode.set(textNode, output);
      if (current !== output) textNode.nodeValue = output;
    });
  };

  scan();
  const observer = new MutationObserver(scan);
  observer.observe(root, { childList: true, subtree: true, characterData: true });
  return () => observer.disconnect();
}

