export function normalizeLanguage(value) {
  return value === "en-US" ? "en-US" : "zh-CN";
}

export function readStoredLanguage(storage = typeof localStorage !== "undefined" ? localStorage : null) {
  try {
    return normalizeLanguage(storage?.getItem(LANGUAGE_STORAGE_KEY));
  } catch {
    return "zh-CN";
  }
}

export function saveStoredLanguage(language, storage = typeof localStorage !== "undefined" ? localStorage : null) {
  const normalized = normalizeLanguage(language);
  try { storage?.setItem(LANGUAGE_STORAGE_KEY, normalized); } catch { /* restricted storage */ }
  return normalized;
}

